// Builds components/software-credits.ts from package-lock.json: the open-source packages the web app
// installs to run (its dependencies and theirs; devDependencies are build and test tools), with their
// licences, for the Credits page. Run it after changing dependencies: `npm run credits`.
// tests/credits-page.test.tsx fails while the list is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Left off the page on purpose. The payment SDK installed today is not in use (billing is off), and
 * no payment provider is named on the site until Scaler chooses one (AGENTS.md, rule 11).
 */
export const HIDDEN = new Set(["@paddle/paddle-node-sdk"]);

/** Platform builds (sharp's and Next's binaries) count only for where the app runs: Linux, x64, glibc. */
function runsOnOurServers(pkg) {
  const fits = (list, value) => !list || list.includes(value);
  return fits(pkg.os, "linux") && fits(pkg.cpu, "x64") && fits(pkg.libc, "glibc");
}

const byNameThenVersion = (a, b) =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : a.version < b.version ? -1 : a.version > b.version ? 1 : 0;

/** @param {{ packages: Record<string, any> }} lock the parsed package-lock.json (lockfile version 3) */
export function softwareCredits(lock) {
  const found = new Map();
  for (const [key, pkg] of Object.entries(lock.packages)) {
    if (!key || pkg.dev || pkg.devOptional || pkg.link || !runsOnOurServers(pkg)) continue;
    const name = pkg.name ?? key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
    if (HIDDEN.has(name)) continue;
    const id = `${name}@${pkg.version}`;
    if (!found.has(id)) found.set(id, { name, version: pkg.version, license: pkg.license ?? "not stated" });
  }
  return [...found.values()].sort(byNameThenVersion);
}

/** The generated file, byte for byte. */
export function render(list) {
  return `// GENERATED by scripts/software-credits.mjs from package-lock.json: the open-source packages the web
// app installs to run, for the Credits page. Regenerate (npm run credits), don't edit.
export type SoftwareCredit = { name: string; version: string; license: string };

export const SOFTWARE_CREDITS: SoftwareCredit[] = ${JSON.stringify(list, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const web = new URL("../", import.meta.url);
  const lock = JSON.parse(readFileSync(new URL("package-lock.json", web), "utf8"));
  const list = softwareCredits(lock);
  writeFileSync(new URL("components/software-credits.ts", web), render(list));
  console.log(`components/software-credits.ts: ${list.length} packages`);
}
